        eprint(f'ANGIF {grip} {vals} {defgrip} ROUTES {routes} &&&&&&&&&&&&&&&& {self.tapslist}')
        for (tap,t,name,c) in self.tapslist:   # for all taps 'tap'
            startidxs.append((len(alldests),tap,name))
            thisdests = {}
            for dest in itertools.chain(routes.get(tap,[]),defroutes.get(tap,[])):
                eprint(f'FUGNO {tap} {dest} {len(startidxs)} {len(alldests)}')
                if not thisdests.get(dest,None):
                    alldests.append((dest,len(thisdests),tap))
                    thisdests[dest] = True
                    eprint(f'DLKUGNO {dest} {thisdests}')
        startidxs.append((len(alldests),'final','dummy for end of list'))  # one extra to end the last set
        self.gripinfo[grip] = [ alldests, startidxs]
        eprint(f'IIIEIEIIE {grip} :: {self.gripinfo[grip]}')
        
