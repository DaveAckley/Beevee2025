    def analyzeXBlock(self,name,props):
        xbpos = props['pos']
        # Derive size
        cols = max(len(props['taps']['N']),len(props['taps']['S']))
        rows = max(len(props['taps']['E']),len(props['taps']['W']))
        eprint("BONGSNI",name,cols,rows)

        props['origin'] = 'NW'

        w = cols
        h = rows
        #props['size'] = [w+2,h+2]
        props['size'] = [w,h]  ## NOT INCLUDING SURROUNDING TAPS!?
        stride = props['stride']
        sw = stride[0]*w+2
        sh = stride[1]*h+2
        hc3w = int((sw+2)/3)
        hc3h = int((sh+2)/3)
        props['hc3size'] = [hc3w,hc3h]
        eprint("ZANSNI",name,props,cols,rows,stride,hc3w,hc3h)

        for side in ('N','S','E','W'):
            offset = self.mapDir(self.growDir(side))
            eprint("ZANS11",side,offset)

            count = 0
            for tap in props['taps'][side]:
                count = count+1
                tappos = addc(smulc(count,offset),xbpos)
                self.generateTAP(tap,name,count,tappos)

