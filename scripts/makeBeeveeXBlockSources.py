    def analyzeOperator(self,tok):
        if not self.codeOps.get(tok):
            self.codeOps[tok] = {}

    def analyzeFunction(self,tok):  # function use
        if not self.codeFuncAddrs.get(tok):
            self.codeFuncAddrs[tok] = None
            

    def analyzeToken(self,tok,funcinfo):
        if funcinfo:
            self.codeIntRam.append((tok,*funcinfo))
        else:
            self.codeIntRam.append(tok)
        if type(tok)==int:
            return
        code = tok[0]
        if code == 'c':
            self.analyzeConstant(tok)
        elif code == 'o':
            self.analyzeOperator(tok)
        elif code == 'f':
            self.analyzeFunction(tok)

    def analyzeCodeInfoFor(self,func,vals):
        eprint(f'ANCIF {func} {vals}')
        funcaddr = len(self.codeIntRam)
        exist = self.codeFuncAddrs.get(func)
        if exist:
            raise Exception(f"MULTIPLY DEFINED FUNCTION: {func} {vals}")
        self.codeFuncAddrs[func] = funcaddr
        first = (func,vals.get('doc',None))
        self.codeFunctions[func] = first[1]
        self.analyzeToken('oENTER',first)
        last = None
        for tok in vals['code']:
            self.analyzeToken(tok,None)
            last = tok
        if last != 'oRETURN':
            self.analyzeToken('oRETURN',('From',func))
        
    def mergeCodeInfo(self):
        ccfg = self.codeCfg
        funcs = ccfg.getRequiredSection('function')
        self.codeIntRam = [('oCALL','fake for returning to top level')]  # list of code ints
        self.codeFunctions = {}  # name -> doc
        self.codeFuncAddrs = {}  # name -> intramaddr
        self.codeConstVals = {}  # name -> constval
        self.codeOps = {}        # name -> ??
        for k,v in funcs.items():
            self.analyzeCodeInfoFor(k,v)

        eprint(f"EXPOC {self.codeIntRam}")
        eprint(f"EXPFAD {self.codeFuncAddrs}")
        eprint(f"EXPCNV {self.codeConstVals}")
        eprint(f"EXPOXS {self.codeOps}")
        eprint(f'CODELD {funcs}')

        ops = ccfg.getRequiredSection('operator')
        eprint(f'OPSPOPS {ops}')

        for k in self.codeOps:
            if not k in ops:
                raise Exception("Undeclared operator:",k)
        for k,v in ops.items():
            if not v.get('impl'):
                v['impl'] = f'return native_{k}(s,g,t,l)'
            eprint(f"DIDIMPL {k},{v}")

    def analyzeTRAKtInfoFor(self,t,vals):
        eprint(f'ANTIF {t} {vals}')
        traktnum = len(self.traktList)
        exist = self.traktMap.get(t)
        if exist:
            raise Exception(f"MULTIPLY DEFINED FUNCTION: {t} {vals}")
        self.traktList.append(t)
        self.traktMap[t] = { 'index' : traktnum }
        if (k := 'mSpeedLeft') in vals:
            speedNotWheel = False
            v1 = vals[k]
            v2 = vals['mSpeedRight']  # raise exception if missing
        elif (k := 'mSpeedMin') in vals:
            speedNotWheel = True
            v1 = vals[k]
            v2 = vals['mSpeedMax']  # ditto
        else:
            raise Exception(f"unrecognized trakt {t} ({vals})")
        if (k := 'mDoneFunc') in vals:
            funcNotOp = True
            done = vals[k]
        elif (k := 'mDoneOp') in vals:
            funcNotOp = False
            done = vals[k]
        else:
            raise Exception(f"trakt {t} missing done info ({vals})")
        self.traktMap[t]['mSpeedNotWheel'] = speedNotWheel
        self.traktMap[t]['mSpeed1'] = v1
        self.traktMap[t]['mSpeed2'] = v2
        self.traktMap[t]['mFuncNotOp'] = funcNotOp
        self.traktMap[t]['mDoneCode'] = done

    def mergeTRAKtInfo(self):
        ccfg = self.codeCfg
        trakts = ccfg.getRequiredSection('trakt')
        self.traktList = []      # name, ..
        self.traktMap = {}       # name -> {stuff}
        self.codeOps = {}        # name -> ??
        for k,v in trakts.items():
            self.analyzeTRAKtInfoFor(k,v)
        eprint(f"MTKIN10 {self.traktMap}")

            
