def xbname(name):
    return "XBlock_"+name

def tapidxname(name):
    if name == "NONE":
        raise Exception("Cannot name a TAP 'NONE'!")
    return "cTAPIDX_"+name

def genSymbol(name):
    return name[0:2]

def addc(*arg):
    return tuple(sum(t) for t in zip(*arg))

def mulc(*arg):
    return tuple(prod(t) for t in zip(*arg))

def smulc(scalar,tup):
    return [ scalar * t for t in tup ]

def saddc(scalar,tup):
    return [ scalar + t for t in tup ]


