    def mergeBrainTAPs(self):
        xb = self.brainCfg.getRequiredSection("xblock")
        for k,v in xb.items():  # per xb
            if not v.get("taps",None):
                v["taps"] = {}
            taps = v["taps"]    # per xb
            eprint(f'BAHOOM {k},{v},{taps}')
            for side in ('N','S','E','W'):
                if not taps.get(side,None):
                    taps[side] = []
            for side,list in taps.items():
                for tap in (*list,'_'):   # make sure HEMP declared even if dtoml doesn't use it..
                    if tap == "_":
                        tap = 'HEMP' # Hidden EMPty
                    eprint(f'NARG {tap},{k},{side}')
                    # add as hidden if not found as sensor or motor
                    if self.taps['sensor'].get(tap) == None and self.taps['motor'].get(tap) == None:
                        self.taps['hidden'][tap] = {'name': tap, 'doc': f'xblock.{k} {v}'}
                        eprint(f'NARGL {self.taps["hidden"][tap]}')
        eprint(f'MERGBNONIC {self.taps}')

    def analyzeGripInfoFor(self,grip,vals,defgrip):
        alldests = []
        startidxs = []
        routes = vals.get('routes',{})
